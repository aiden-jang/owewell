/**
 * Generates public/og.svg + public/og.png from the theme palette.
 *
 *   node scripts/og.mjs
 *
 * Why generated rather than hand-drawn: the share card is what shows up in iMessage before anyone has
 * opened the app, and it used to be a hardcoded violet-to-cyan gradient on near-black. So the moment the
 * palette changed, every link anyone had ever sent was advertising the previous design.
 *
 * It cannot follow a per-person theme — a link preview is fetched once by Apple/Meta/Slack and cached,
 * with no user and no localStorage — so it is built to match DEFAULT_THEME. That is the honest ceiling
 * here, and it means this script has to be re-run whenever the shipped default changes.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, rmSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const PUBLIC = resolve(HERE, '../public');
const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';

/** Read the default and the palettes out of source, so this can never disagree with the app. */
function palette() {
  const theme = readFileSync(resolve(HERE, '../src/lib/theme.ts'), 'utf8');
  const name = /SHIPPED_THEME: ThemeName = '(\w+)'/.exec(theme)?.[1];
  if (!name) throw new Error('Could not find SHIPPED_THEME in src/lib/theme.ts');

  const src = readFileSync(resolve(HERE, '../src/lib/contrast.ts'), 'utf8');
  const constName = name === 'warm' ? 'WARM' : 'DARK';
  const block = new RegExp(`export const ${constName}: Palette = \\{([^}]+)\\}`).exec(src)?.[1];
  if (!block) throw new Error(`Could not find ${constName} in src/lib/contrast.ts`);

  const p = Object.fromEntries([...block.matchAll(/(\w+):\s*'(#[0-9a-fA-F]{6})'/g)].map((m) => [m[1], m[2]]));
  return { name, ...p };
}

const p = palette();
console.log(`building og card for the "${p.name}" theme`);

// Mark + wordmark only. A tagline turns to illegible specks in a share-sheet thumbnail, and the content
// is centred so consumers that crop toward a square still show something on-brand.
const svg = `<svg width="1200" height="630" viewBox="0 0 1200 630" xmlns="http://www.w3.org/2000/svg">
  <!-- GENERATED by scripts/og.mjs from DEFAULT_THEME (${p.name}). Do not edit by hand. -->
  <rect width="1200" height="630" fill="${p.canvas}" />
  <g transform="translate(507, 150)">
    <rect width="186" height="186" rx="50" fill="${p.accent}" />
    <g transform="translate(55, 37) scale(0.31)">
      <path d="M150 96 h212 v300 l-30 -20 -30 20 -30 -20 -30 20 -30 -20 -32 20 z" fill="${p.accentInk}" fill-opacity="0.95" />
      <path d="M203 178 h106 M203 240 h106 M203 302 h62" stroke="${p.accent}" stroke-width="25" stroke-linecap="round" />
    </g>
  </g>
  <text x="600" y="420" text-anchor="middle" font-family="Inter, system-ui, -apple-system, sans-serif"
        font-size="86" font-weight="700" letter-spacing="-3" fill="${p.ink}">owewell</text>
  <text x="600" y="482" text-anchor="middle" font-family="Inter, system-ui, -apple-system, sans-serif"
        font-size="32" font-weight="500" fill="${p.muted}">Split the bill. Keep the friends.</text>
</svg>
`;
writeFileSync(resolve(PUBLIC, 'og.svg'), svg);
console.log('public/og.svg');

// Every scraper wants a raster. Chrome renders the SVG we just wrote, so the two cannot drift.
const shim = resolve(PUBLIC, '.og.html');
writeFileSync(
  shim,
  `<!doctype html><meta charset="utf-8"><style>html,body{margin:0;width:1200px;height:630px;overflow:hidden}</style>${svg}`,
);
try {
  execFileSync(
    CHROME,
    [
      '--headless',
      '--disable-gpu',
      '--hide-scrollbars',
      '--window-size=1200,630',
      `--screenshot=${resolve(PUBLIC, 'og.png')}`,
      `file://${shim}`,
    ],
    { stdio: 'ignore' },
  );
} finally {
  rmSync(shim, { force: true });
}
console.log('public/og.png  1200x630');
